#!/usr/bin/env python3
"""
sync_agent_adapters.py — Generate the Claude Code /e4:* commands from the shared e4 skills.

Single source of truth: the agent-neutral workflows live in
    agents-config/.agents/skills/e4-<name>/SKILL.md     (read natively by Copilot and Cursor)
Claude Code needs a few things the neutral text can't carry — `!`cmd`` context injection,
$ARGUMENTS, hook installation, the /e4: namespace — so each command is rendered as
    claude-config/overlays/<name>.md  (frontmatter + named regions)
  + the skill body, with every <!-- adapter:X -->default<!-- /adapter:X --> region replaced by the
    overlay's <!-- region:X --> text (or kept as-is when the overlay doesn't define X)
  → claude-config/.claude/commands/e4/<name>.md        (GENERATED — never hand-edit)

Owns generation only; it does not install anything into a project.

Usage:
    python sync_agent_adapters.py            # regenerate the Claude commands
    python sync_agent_adapters.py --check    # exit 1 if a generated command is stale (CI / tests)
    python sync_agent_adapters.py --root /path/to/e4   # default: this script's repo
"""
from __future__ import annotations
import argparse
import re
import sys
from pathlib import Path

WORKFLOWS = ("init", "resume", "new-task", "end-session")
SKILLS_DIR = Path("agents-config/.agents/skills")
OVERLAYS_DIR = Path("claude-config/overlays")
COMMANDS_DIR = Path("claude-config/.claude/commands/e4")
FOOTER = ("<!-- e4 · forged by Omar Araby & contributors · add your name to CONTRIBUTORS.md "
          "when you extend these commands -->\n")

_FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)
_REGION = re.compile(r"<!-- region:([\w-]+) -->\n(.*?)\n?<!-- /region:\1 -->", re.DOTALL)
# A region whose markers sit on their own lines is a block: the marker lines are consumed too.
_BLOCK = re.compile(r"^<!-- adapter:([\w-]+) -->\n(.*?)^<!-- /adapter:\1 -->\n",
                    re.DOTALL | re.MULTILINE)
_INLINE = re.compile(r"<!-- adapter:([\w-]+) -->(.*?)<!-- /adapter:\1 -->", re.DOTALL)
# `/e4-end-session` → `/e4:end-session`, but never inside a path such as `skills/e4-init/`.
_SLASH_NAME = re.compile(r"(?<![\w.])/e4-(%s)\b(?!/)" % "|".join(map(re.escape, WORKFLOWS)))
_TITLE = re.compile(r"^# e4-(%s)\b" % "|".join(map(re.escape, WORKFLOWS)), re.MULTILINE)


def split_frontmatter(text: str) -> tuple[str, str]:
    """Return (frontmatter without fences, body). Raises ValueError if there is no frontmatter."""
    m = _FRONTMATTER.match(text.replace("\r\n", "\n"))
    if not m:
        raise ValueError("missing YAML frontmatter")
    return m.group(1), text.replace("\r\n", "\n")[m.end():]


def parse_overlay(text: str) -> tuple[str, dict[str, str]]:
    """Return (command frontmatter, {region name: replacement text})."""
    fm, body = split_frontmatter(text)
    return fm, {name: content for name, content in _REGION.findall(body)}


def apply_regions(body: str, regions: dict[str, str]) -> str:
    """Replace adapter regions with overlay text; undefined regions fall back to their default."""
    def block(m: re.Match) -> str:
        content = regions.get(m.group(1), m.group(2).rstrip("\n"))
        return content + "\n" if content else ""

    def inline(m: re.Match) -> str:
        return regions.get(m.group(1), m.group(2))

    return _INLINE.sub(inline, _BLOCK.sub(block, body))


def render_command(name: str, skill_text: str, overlay_text: str) -> str:
    """Render one Claude command file from its shared skill and Claude overlay."""
    _, skill_body = split_frontmatter(skill_text)
    fm, regions = parse_overlay(overlay_text)
    body = apply_regions(skill_body, regions)
    body = _TITLE.sub(lambda m: f"# /e4:{m.group(1)}", body)
    body = _SLASH_NAME.sub(lambda m: f"/e4:{m.group(1)}", body)
    leftover = _INLINE.search(body)
    if leftover:
        raise ValueError(f"{name}: unbalanced adapter region '{leftover.group(1)}'")
    notice = (f"# GENERATED from agents-config/.agents/skills/e4-{name}/SKILL.md + "
              f"claude-config/overlays/{name}.md by automation/python/sync_agent_adapters.py "
              f"— edit those, then regenerate. Do not edit this file.")
    return f"---\n{fm}\n{notice}\n---\n{body.rstrip()}\n\n{FOOTER}"


def build(root: Path) -> dict[Path, str]:
    """Return {output path: rendered content} for every workflow."""
    out: dict[Path, str] = {}
    for name in WORKFLOWS:
        skill = root / SKILLS_DIR / f"e4-{name}" / "SKILL.md"
        overlay = root / OVERLAYS_DIR / f"{name}.md"
        out[root / COMMANDS_DIR / f"{name}.md"] = render_command(
            name, skill.read_text(encoding="utf-8"), overlay.read_text(encoding="utf-8"))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate Claude /e4:* commands from shared skills")
    ap.add_argument("--root", default=str(Path(__file__).resolve().parents[2]),
                    help="e4 repository root (default: this script's repo)")
    ap.add_argument("--check", action="store_true",
                    help="Don't write; exit 1 if any generated command is out of date")
    args = ap.parse_args()
    root = Path(args.root).resolve()

    try:
        rendered = build(root)
    except (OSError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    stale = []
    for path, content in rendered.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current is not None and current.replace("\r\n", "\n") == content:
            print(f"ok    {path.relative_to(root)}")
            continue
        stale.append(path)
        if args.check:
            print(f"STALE {path.relative_to(root)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"write {path.relative_to(root)}")

    if args.check and stale:
        print("Run: python automation/python/sync_agent_adapters.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
